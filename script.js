// Função chamada quando o usuário clica no botão 1
function alterarTexto1() {

    // Localiza o elemento com id="texto"
    let paragrafo = document.getElementById("texto");

    // Altera o conteúdo do parágrafo
    paragrafo.innerHTML = "Viu, o JavaScript alterou este texto!";
}

